/**
 * Символы, которым нет места в именах и названиях, что видит пользователь.
 * Строки — для класса символов в регулярке (в том числе в `pattern` схемы
 * TypeBox, где `\uXXXX` записывается удвоенным слэшем).
 */

/**
 * Управляющие (Cc: `U+0000–U+001F`, `U+007F–U+009F`) плюс разделители строк и
 * абзацев. NUL Postgres не принимает в тексте — запрос падал пятисоткой, — а
 * перевод строки ломает вывод и заголовки, в которые имя попадает при отдаче.
 */
export const CONTROL_CHARACTERS = '\\u0000-\\u001F\\u007F-\\u009F\\u2028\\u2029'

/**
 * Управление направлением текста: метки, встраивания, переопределения и
 * изоляции. `счёт‮fdp.exe` выглядит в списке как `счётexe.pdf` —
 * подделка видимого имени, хотя настоящее расширение берётся из таблицы
 * форматов. Обычному тексту на иврите или арабском они не нужны.
 */
export const BIDI_CONTROLS = '\\u061C\\u200E\\u200F\\u202A-\\u202E\\u2066-\\u2069'

/** Шаблон схемы: строка целиком без управляющих символов. */
export const WITHOUT_CONTROL_CHARACTERS = `^[^${CONTROL_CHARACTERS}]*$`
