/**
 * Id всех таблиц — uuid (`@default(uuid(7))`), а колонки — `text`. Что угодно
 * другое из адреса доезжало бы до Postgres как есть, и `%00` в `:id` ронял
 * запрос пятисоткой: NUL в тексте Postgres не принимает. Поэтому id из пути
 * сверяется с форматом до базы, и «не uuid» отвечает тем же 404, что и
 * несуществующий id, — для клиента это одно и то же.
 */
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i

export const isUuid = (value: string): boolean => UUID.test(value)
